-- =============================================================================
-- ERP MAQUILA - ESQUEMA INICIAL PARA SUPABASE (PostgreSQL)
-- Traducción del antiguo database_schema.sql (MySQL) a PostgreSQL.
--
-- Cómo aplicarla:
--   * Supabase CLI:   supabase link --project-ref <ref> && supabase db push
--   * Sin CLI:        copie este archivo en el SQL Editor del panel de Supabase y ejecútelo.
--
-- Seguridad: el backend (server.ts) se conecta directamente a Postgres con la
-- cadena DATABASE_URL (rol "postgres"), que ignora RLS. Todas las tablas tienen
-- RLS habilitado SIN políticas, de modo que la API pública de Supabase
-- (PostgREST con las llaves anon/authenticated) no puede leer ni escribir nada.
-- =============================================================================

-- =============================================================================
-- 1. TABLAS CATÁLOGO
-- =============================================================================

CREATE TABLE roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE order_status (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    is_terminal BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE production_status (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE production_stages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    sequence_order INTEGER NOT NULL
);

CREATE TABLE product_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE attribute_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    input_component VARCHAR(100) NOT NULL,
    requires_catalog_value BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sizes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL,
    sort_order INTEGER NOT NULL,
    gender VARCHAR(50) NOT NULL DEFAULT 'unisex'
);

-- =============================================================================
-- 2. TABLAS OPERACIONALES
-- =============================================================================

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role_id INTEGER NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    nit VARCHAR(20),
    nrc VARCHAR(20),
    nombre_comercial VARCHAR(255),
    actividad_economica VARCHAR(255),
    direccion TEXT,
    telefono VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- MySQL comparaba correos sin distinguir mayúsculas; Postgres sí distingue.
-- El índice único sobre lower(email) mantiene el comportamiento anterior.
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    product_type_id INTEGER NOT NULL REFERENCES product_types(id) ON DELETE RESTRICT
);

CREATE TABLE product_attributes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    attribute_name VARCHAR(255) NOT NULL,
    attribute_type_id INTEGER NOT NULL REFERENCES attribute_types(id) ON DELETE RESTRICT,
    is_required BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX product_attributes_product_id_idx ON product_attributes (product_id);

CREATE TABLE product_attribute_values (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id INTEGER NOT NULL REFERENCES product_attributes(id) ON DELETE CASCADE,
    value VARCHAR(255) NOT NULL,
    price_modifier NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX product_attribute_values_attribute_id_idx ON product_attribute_values (attribute_id);

CREATE TABLE product_sizes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    size_id INTEGER NOT NULL REFERENCES sizes(id) ON DELETE RESTRICT,
    price_modifier NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_product_size UNIQUE (product_id, size_id)
);

CREATE TABLE orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    client_name VARCHAR(255) NOT NULL,
    created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status_id INTEGER NOT NULL REFERENCES order_status(id) ON DELETE RESTRICT,
    priority VARCHAR(50) NOT NULL DEFAULT 'medium'
        CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    notes TEXT,
    client_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    client_confirmed_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    production_start_date DATE NOT NULL,
    estimated_delivery_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (estimated_delivery_date >= production_start_date)
);
CREATE INDEX orders_client_id_idx ON orders (client_id);
CREATE INDEX orders_estimated_delivery_date_idx ON orders (estimated_delivery_date);

CREATE TABLE order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    custom_notes TEXT
);
CREATE INDEX order_items_order_id_idx ON order_items (order_id);

CREATE TABLE order_item_attributes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id INTEGER NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    attribute_id INTEGER NOT NULL REFERENCES product_attributes(id) ON DELETE RESTRICT,
    attribute_value_id INTEGER REFERENCES product_attribute_values(id) ON DELETE SET NULL,
    custom_value TEXT,
    value_label VARCHAR(255) NOT NULL,
    price_modifier_snapshot NUMERIC(10, 2) NOT NULL DEFAULT 0.00
);
CREATE INDEX order_item_attributes_order_item_id_idx ON order_item_attributes (order_item_id);

CREATE TABLE order_item_sizes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id INTEGER NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    product_size_id INTEGER NOT NULL REFERENCES product_sizes(id) ON DELETE RESTRICT,
    size_label VARCHAR(50) NOT NULL,
    price_modifier_snapshot NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    quantity INTEGER NOT NULL CHECK (quantity > 0)
);
CREATE INDEX order_item_sizes_order_item_id_idx ON order_item_sizes (order_item_id);

CREATE TABLE order_item_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id INTEGER NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    file_url TEXT NOT NULL,
    file_type VARCHAR(100) NOT NULL DEFAULT 'image/jpeg',
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX order_item_files_order_item_id_idx ON order_item_files (order_item_id);

-- =============================================================================
-- 3. FACTURACIÓN, PAGOS, PRODUCCIÓN Y CAPACIDAD
-- =============================================================================

CREATE TABLE invoice_sequences (
    year INTEGER PRIMARY KEY,
    next_number INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE invoices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    invoice_number VARCHAR(100) NOT NULL UNIQUE,
    codigo_generacion VARCHAR(36),
    numero_control VARCHAR(50),
    sello_recepcion VARCHAR(100),
    fecha_hora_generacion TIMESTAMP,
    receptor_nombre VARCHAR(255),
    receptor_nit VARCHAR(20),
    receptor_nrc VARCHAR(20),
    receptor_actividad_economica VARCHAR(255),
    receptor_direccion TEXT,
    receptor_telefono VARCHAR(50),
    receptor_correo VARCHAR(255),
    receptor_nombre_comercial VARCHAR(255),
    subtotal NUMERIC(10, 2) NOT NULL,
    tax NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    ventas_no_sujetas NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    ventas_exentas NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    ventas_gravadas NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    iva_retenido NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    iva_percibido NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    retencion_renta NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    discount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total NUMERIC(10, 2) NOT NULL,
    invoice_type VARCHAR(50) NOT NULL
        CHECK (invoice_type IN ('consumidor_final', 'credito_fiscal')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX invoices_order_id_idx ON invoices (order_id);

CREATE TABLE payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(50) NOT NULL
        CHECK (payment_method IN ('efectivo', 'tarjeta', 'transferencia')),
    notes TEXT,
    registered_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX payments_order_id_idx ON payments (order_id);

CREATE TABLE production_tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    order_item_id INTEGER NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    stage_id INTEGER NOT NULL REFERENCES production_stages(id) ON DELETE RESTRICT,
    assigned_to INTEGER REFERENCES users(id) ON DELETE SET NULL,
    status_id INTEGER NOT NULL DEFAULT 1 REFERENCES production_status(id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date_estimated DATE,
    end_date_actual DATE,
    workload_points INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    task_type VARCHAR(50) NOT NULL DEFAULT 'normal'
        CHECK (task_type IN ('normal', 'repair', 'remake'))
);
CREATE INDEX production_tasks_order_id_idx ON production_tasks (order_id);
CREATE INDEX production_tasks_order_item_id_idx ON production_tasks (order_item_id);
CREATE INDEX production_tasks_start_date_stage_idx ON production_tasks (start_date, stage_id);
CREATE INDEX production_tasks_status_id_idx ON production_tasks (status_id);

CREATE TABLE work_calendar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_date DATE NOT NULL,
    stage_id INTEGER NOT NULL REFERENCES production_stages(id) ON DELETE RESTRICT,
    max_capacity_points INTEGER NOT NULL DEFAULT 500 CHECK (max_capacity_points >= 0),
    is_working_day BOOLEAN NOT NULL DEFAULT TRUE,
    notes VARCHAR(255),
    CONSTRAINT uq_date_stage UNIQUE (work_date, stage_id)
);

CREATE TABLE rework_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_task_id INTEGER NOT NULL REFERENCES production_tasks(id) ON DELETE CASCADE,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    rework_type VARCHAR(50) NOT NULL CHECK (rework_type IN ('arreglo', 'hacer_de_nuevo')),
    description TEXT NOT NULL,
    created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    stage_id INTEGER NOT NULL REFERENCES production_stages(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX rework_events_order_id_idx ON rework_events (order_id);

CREATE TABLE password_reset_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX password_reset_requests_email_idx ON password_reset_requests (lower(email));

